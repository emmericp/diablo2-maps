// D2's act numbering is 0..4 internally (DLL ABI), displayed as 1..5 to the
// player. Use ActId in our code and convert at the D2 boundary via ActNo().
enum class ActId : uint32_t {
    Act1 = 0,
    Act2 = 1,
    Act3 = 2,
    Act4 = 3,
    Act5 = 4,
};

constexpr uint32_t ActNo(ActId a) { return static_cast<uint32_t>(a); }

